    local spec = table.concat({
        "fg:" .. palette.fg,
        "bg:" .. palette.bg,
        "hl:" .. palette.green,
        "fg+:" .. palette.fg,
        "bg+:" .. palette.gray2,
        "hl+:" .. palette.green,
        "info:" .. palette.gray3,
        "prompt:" .. palette.orange,
        "pointer:" .. palette.pink,
        "marker:" .. palette.purple,
        "spinner:" .. palette.orange,
        "header:" .. palette.light_blue,
        "border:" .. palette.gray3,
        "label:" .. palette.orange,
        "query:" .. palette.fg,
        "gutter:" .. palette.bg,
        "separator:" .. palette.gray2,
        "scrollbar:" .. palette.gray3,
    }, ",")

    local lines = {
        HASH_BANNER,
        "# Neolux colorscheme for fzf",
        "# Usage: source /path/to/neolux/extras/fzf/neolux.sh",
        "",
        fmt('export FZF_DEFAULT_OPTS="${FZF_DEFAULT_OPTS:+${FZF_DEFAULT_OPTS} }--color=%s"', spec),
    }

    return ensure_trailing_newline(table.concat(lines, "\n"))
end

local function render_tmux()
    local lines = {
        HASH_BANNER,
        "# Neolux colorscheme for tmux",
        "# Usage: add 'source-file /path/to/neolux/extras/tmux/neolux.tmux' to ~/.tmux.conf",
        "",
        fmt('set -g mode-style "fg=%s,bg=%s,bold"', palette.bg, palette.orange),
        fmt('set -g message-style "fg=%s,bg=%s,bold"', palette.orange, palette.gray1),
        fmt('set -g message-command-style "fg=%s,bg=%s,bold"', palette.light_blue, palette.gray1),
        "",
        fmt('set -g pane-border-style "fg=%s"', palette.gray2),
        fmt('set -g pane-active-border-style "fg=%s"', palette.orange),
        "",
        'set -g status "on"',
        'set -g status-justify "left"',
        fmt('set -g status-style "fg=%s,bg=%s"', palette.fg, palette.gray1),
        'set -g status-left-length "100"',
        'set -g status-right-length "100"',
        "",
        fmt(
            'set -g status-left "#[fg=%s,bg=%s,bold]#{?client_prefix,#[bg=%s],} #S #[default] "',
            palette.bg,
            palette.light_blue,
            palette.orange
        ),
        fmt(
            'set -g status-right "#[fg=%s,bg=%s] %%Y-%%m-%%d %%H:%%M #[fg=%s,bg=%s,bold] #h "',
            palette.fg,
            palette.gray2,
            palette.bg,
            palette.light_blue
        ),
        "",
        'set -g window-status-separator ""',
        fmt('set -g window-status-style "fg=%s,bg=%s"', palette.gray3, palette.gray1),
        fmt('set -g window-status-current-style "fg=%s,bg=%s,bold"', palette.bg, palette.orange),
        fmt('set -g window-status-activity-style "fg=%s,bg=%s,bold"', palette.yellow, palette.gray1),
        fmt('set -g window-status-bell-style "fg=%s,bg=%s,bold"', palette.bg, palette.pink),
        'set -g window-status-format " #I:#W "',
        'set -g window-status-current-format " #I:#W "',
        "",
        fmt('set -g clock-mode-colour "%s"', palette.light_blue),
    }

    return ensure_trailing_newline(table.concat(lines, "\n"))
end

local targets = {
    { path = "extras/wezterm/neolux.lua", content = render_wezterm_lua() },
    { path = "extras/wezterm/neolux.toml", content = render_wezterm_toml() },
    { path = "extras/ghostty/neolux", content = render_ghostty("neolux") },
    { path = "extras/ghostty/neolux.conf", content = render_ghostty("neolux.conf") },
    { path = "extras/kitty/neolux.conf", content = render_kitty() },
    { path = "extras/fzf/neolux.sh", content = render_fzf() },
    { path = "extras/tmux/neolux.tmux", content = render_tmux() },
}

local check_mode = vim.env.NEOLUX_EXTRAS_CHECK == "1"

if check_mode then
    local drifted = {}
    for _, target in ipairs(targets) do
        local f = io.open(target.path, "rb")
        local existing = f and f:read("*a") or nil
        if f then
            f:close()
        end
        if existing ~= target.content then
            drifted[#drifted + 1] = target.path
        end
    end

    if #drifted > 0 then
        print("extras drift detected in:")
        for _, p in ipairs(drifted) do
            print("  - " .. p)
        end
        vim.cmd("cq 1")
    else
        print(fmt("extras check OK (%d files in sync)", #targets))
    end
else
    for _, target in ipairs(targets) do
        local dir = vim.fn.fnamemodify(target.path, ":h")
        vim.fn.mkdir(dir, "p")
        local f = assert(io.open(target.path, "wb"))
        assert(f:write(target.content))
        f:close()
        print("generated: " .. target.path)
    end
end
