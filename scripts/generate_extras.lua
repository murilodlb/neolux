local palette = require("neolux.palette")
local config = require("neolux.config")

local fmt = string.format

local ansi = {}
for i = 1, 16 do
    local key = config.terminal_colors[i]
    ansi[i - 1] = assert(palette[key], "missing palette key for terminal_colors[" .. i .. "]: " .. tostring(key))
end

local LUA_BANNER = "-- Auto-generated by scripts/generate_extras.lua — do not edit manually"
local HASH_BANNER = "# Auto-generated by scripts/generate_extras.lua — do not edit manually"

local function ensure_trailing_newline(content)
    return content:gsub("\n*$", "\n")
end

local function render_wezterm_lua()
    local lines = {
        LUA_BANNER,
        "-- Neolux colorscheme for WezTerm",
        "-- Usage in wezterm.lua:",
        '-- config.colors = dofile("/path/to/neolux/extras/wezterm/neolux.lua")',
        "",
        "return {",
        "    -- Default Colors",
        fmt("    foreground = %q,", palette.fg),
        fmt("    background = %q,", palette.bg),
        "",
        "    -- Cursor Colors",
        fmt("    cursor_bg = %q,", palette.orange),
        fmt("    cursor_fg = %q,", palette.bg),
        fmt("    cursor_border = %q,", palette.orange),
        "",
        "    -- Selection Colors",
        fmt("    selection_fg = %q,", palette.bg),
        fmt("    selection_bg = %q,", palette.fg),
        "",
        "    -- UI Chrome",
        fmt("    scrollbar_thumb = %q,", palette.gray3),
        fmt("    split = %q,", palette.gray3),
        "",
        "    -- Standard ANSI Colors (0-7)",
        "    ansi = {",
    }

    for i = 0, 7 do
        lines[#lines + 1] = fmt("        %q,", ansi[i])
    end

    lines[#lines + 1] = "    },"
    lines[#lines + 1] = ""
    lines[#lines + 1] = "    -- Bright ANSI Colors (8-15)"
    lines[#lines + 1] = "    brights = {"

    for i = 8, 15 do
        lines[#lines + 1] = fmt("        %q,", ansi[i])
    end

    local tab_lines = {
        "    },",
        "",
        "    -- Tab Bar",
        "    tab_bar = {",
        fmt("        background = %q,", palette.bg),
        "        active_tab = {",
        fmt("            bg_color = %q,", palette.bg),
        fmt("            fg_color = %q,", palette.fg),
        '            intensity = "Bold",',
        "        },",
        "        inactive_tab = {",
        fmt("            bg_color = %q,", palette.gray1),
        fmt("            fg_color = %q,", palette.gray3),
        "        },",
        "        inactive_tab_hover = {",
        fmt("            bg_color = %q,", palette.gray2),
        fmt("            fg_color = %q,", palette.fg),
        "        },",
        "        new_tab = {",
        fmt("            bg_color = %q,", palette.gray1),
        fmt("            fg_color = %q,", palette.gray3),
        "        },",
        "        new_tab_hover = {",
        fmt("            bg_color = %q,", palette.orange),
        fmt("            fg_color = %q,", palette.bg),
        '            intensity = "Bold",',
        "        },",
        "    },",
        "}",
    }

    for i = 1, #tab_lines do
        lines[#lines + 1] = tab_lines[i]
    end

    return ensure_trailing_newline(table.concat(lines, "\n"))
end

